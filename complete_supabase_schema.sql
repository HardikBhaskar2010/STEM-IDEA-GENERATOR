-- ============================================================================
-- TABLE: users
-- Guest users with randomly generated IDs (no authentication required)
-- ============================================================================
CREATE TABLE public.users (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    guest_id VARCHAR(255) UNIQUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    last_active TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    preferences JSONB DEFAULT '{}',
    metadata JSONB DEFAULT '{}'
);

-- ============================================================================
-- TABLE: components
-- Electronics components with detailed specifications
-- NOTE: price is stored as VARCHAR to include currency symbol formatting
-- NOTE: stock is stored as VARCHAR ('In Stock', 'Out of Stock', 'Limited')
-- ============================================================================
CREATE TABLE public.components (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    description TEXT,
    price VARCHAR(50),
    stock VARCHAR(50) DEFAULT 'In Stock',
    stock_count INTEGER DEFAULT 0,
    manufacturer VARCHAR(255),
    model_number VARCHAR(100),
    datasheet_url TEXT,
    image_url TEXT,
    specifications JSONB DEFAULT '{}',
    tags TEXT[] DEFAULT '{}',
    dimensions JSONB DEFAULT '{}',
    weight DECIMAL(8,3),
    operating_voltage_min DECIMAL(5,2),
    operating_voltage_max DECIMAL(5,2),
    operating_current DECIMAL(8,3),
    power_consumption DECIMAL(8,3),
    interface_type VARCHAR(100),
    pin_count INTEGER,
    package_type VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ============================================================================
-- TABLE: projects
-- User's saved project ideas (generated by AI)
-- ============================================================================
CREATE TABLE public.projects (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
    title VARCHAR(500) NOT NULL,
    description TEXT,
    difficulty VARCHAR(50),
    estimated_time VARCHAR(100),
    estimated_cost VARCHAR(100),
    components TEXT[] DEFAULT '{}',
    skills TEXT[] DEFAULT '{}',
    steps TEXT[] DEFAULT '{}',
    status VARCHAR(50) DEFAULT 'planning',
    progress INTEGER DEFAULT 0 CHECK (progress >= 0 AND progress <= 100),
    notes TEXT DEFAULT '',
    starred BOOLEAN DEFAULT false,
    tags TEXT[] DEFAULT '{}',
    completed_steps INTEGER[] DEFAULT '{}',
    generated_from_params JSONB DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ============================================================================
-- TABLE: chat_messages
-- AI guidance chat messages for each project
-- ============================================================================
CREATE TABLE public.chat_messages (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    project_id UUID REFERENCES public.projects(id) ON DELETE CASCADE,
    user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
    session_id VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    content TEXT NOT NULL,
    message_type VARCHAR(50) DEFAULT 'text',
    metadata JSONB DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ============================================================================
-- TABLE: component_reviews
-- User reviews and ratings for components
-- ============================================================================
CREATE TABLE public.component_reviews (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    component_id UUID REFERENCES public.components(id) ON DELETE CASCADE,
    user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
    user_name VARCHAR(255),
    rating INTEGER CHECK (rating >= 1 AND rating <= 5),
    review_text TEXT,
    pros TEXT[],
    cons TEXT[],
    use_case TEXT,
    difficulty_level VARCHAR(20) CHECK (difficulty_level IN ('Beginner', 'Intermediate', 'Advanced', 'Expert')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ============================================================================
-- TABLE: component_projects
-- Example projects using components
-- ============================================================================
CREATE TABLE public.component_projects (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    component_id UUID REFERENCES public.components(id) ON DELETE CASCADE,
    project_name VARCHAR(255) NOT NULL,
    project_description TEXT,
    project_url TEXT,
    difficulty_level VARCHAR(20) CHECK (difficulty_level IN ('Beginner', 'Intermediate', 'Advanced', 'Expert')),
    estimated_time VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ============================================================================
-- TABLE: component_alternatives
-- Alternative/similar components
-- ============================================================================
CREATE TABLE public.component_alternatives (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    component_id UUID REFERENCES public.components(id) ON DELETE CASCADE,
    alternative_id UUID REFERENCES public.components(id) ON DELETE CASCADE,
    reason TEXT,
    compatibility_score INTEGER CHECK (compatibility_score >= 1 AND compatibility_score <= 10),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

