CREATE OR REPLACE FUNCTION get_component_details(component_uuid UUID)
RETURNS JSON AS $$
DECLARE
    result JSON;
BEGIN
    SELECT json_build_object(
        'component', row_to_json(c),
        'reviews', COALESCE(reviews.reviews, '[]'::json),
        'projects', COALESCE(projects.projects, '[]'::json),
        'alternatives', COALESCE(alternatives.alternatives, '[]'::json),
        'stats', json_build_object(
            'average_rating', COALESCE((SELECT AVG(rating) FROM public.component_reviews WHERE component_id = c.id), 0),
            'review_count', (SELECT COUNT(*) FROM public.component_reviews WHERE component_id = c.id),
            'project_count', (SELECT COUNT(*) FROM public.component_projects WHERE component_id = c.id),
            'alternative_count', (SELECT COUNT(*) FROM public.component_alternatives WHERE component_id = c.id)
        )
    ) INTO result
    FROM public.components c
    LEFT JOIN LATERAL (
        SELECT json_agg(row_to_json(rev)) as reviews
        FROM public.component_reviews rev
        WHERE rev.component_id = c.id
    ) reviews ON true
    LEFT JOIN LATERAL (
        SELECT json_agg(row_to_json(proj)) as projects
        FROM public.component_projects proj
        WHERE proj.component_id = c.id
    ) projects ON true
    LEFT JOIN LATERAL (
        SELECT json_agg(
            json_build_object(
                'id', alt_comp.id,
                'name', alt_comp.name,
                'category', alt_comp.category,
                'reason', alt.reason,
                'compatibility_score', alt.compatibility_score
            )
        ) as alternatives
        FROM public.component_alternatives alt
        JOIN public.components alt_comp ON alt.alternative_id = alt_comp.id
        WHERE alt.component_id = c.id
    ) alternatives ON true
    WHERE c.id = component_uuid;
    
    RETURN result;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION get_user_projects(user_guest_id VARCHAR)
RETURNS JSON AS $$
DECLARE
    result JSON;
    user_uuid UUID;
BEGIN
    SELECT id INTO user_uuid FROM public.users WHERE guest_id = user_guest_id;
    
    IF user_uuid IS NULL THEN
        RETURN '[]'::json;
    END IF;
    
    SELECT json_agg(
        json_build_object(
            'project', row_to_json(p),
            'chat_count', (SELECT COUNT(*) FROM public.chat_messages WHERE project_id = p.id)
        ) ORDER BY p.created_at DESC
    ) INTO result
    FROM public.projects p
    WHERE p.user_id = user_uuid;
    
    RETURN COALESCE(result, '[]'::json);
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION get_project_chat_history(project_uuid UUID, message_limit INTEGER DEFAULT 100)
RETURNS JSON AS $$
DECLARE
    result JSON;
BEGIN
    SELECT json_agg(row_to_json(cm) ORDER BY cm.created_at ASC) INTO result
    FROM (
        SELECT * FROM public.chat_messages
        WHERE project_id = project_uuid
        ORDER BY created_at DESC
        LIMIT message_limit
    ) cm;
    
    RETURN COALESCE(result, '[]'::json);
END;
$$ LANGUAGE plpgsql;

